-- 001_schema.sql -- the mirror table, its anomaly view, and the bookkeeping.
--
-- APPLIED FILES ARE IMMUTABLE. pgmirror.apply_migrations records this file's
-- sha256 and refuses to continue if the bytes change after it has been applied.
-- A schema change is a NEW numbered file, never an edit to this one. In
-- particular CREATE OR REPLACE VIEW cannot change a view's COLUMN LIST -- that
-- needs an explicit DROP VIEW in a new file.
--
-- Every statement here is re-runnable: applying twice leaves the same catalog.

CREATE SCHEMA IF NOT EXISTS mindhive;      -- owner-only: the mirror itself
CREATE SCHEMA IF NOT EXISTS mindhive_ro;   -- the reader's entire universe (views only)

CREATE TABLE IF NOT EXISTS mindhive.events (
    -- Identity only. BIGINT identity, not BIGSERIAL, because the ordering
    -- contract is derived from (ts_key, segment, seg_line) and must NOT depend
    -- on this column. It is honoured as the requested `global_seq BIGINT PK`;
    -- what changed is that correctness no longer rests on it. GENERATED BY
    -- DEFAULT (not ALWAYS) so a rebuild may re-seed it explicitly if an
    -- operator ever wants reproducible ids.
    global_seq  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Namespace scope. TEXT because paths.normalize() emits a kebab slug of
    -- unbounded length; no VARCHAR(n) because a cap here can only ever reject a
    -- real namespace. COLLATE "C" so ordering and equality are byte-wise,
    -- matching Python's code-point comparison exactly.
    project     TEXT COLLATE "C" NOT NULL,

    -- The SOURCE FILE NAME verbatim, e.g. "2c3835ba-....jsonl". This is the
    -- second sort key of events.read_all -- the filename, NOT the session_id
    -- field. Storing it makes the file order DERIVABLE from the row rather than
    -- assumed from insert order. TEXT + COLLATE "C" because it is compared and
    -- ordered against Python str values. NOT NULL: every mirrored row came from
    -- a file.
    segment     TEXT COLLATE "C" NOT NULL,

    -- The 0-based index from enumerate(splitlines()) -- counting blank and
    -- malformed lines, because that is what the file order counts. INTEGER, not
    -- BIGINT: 2^31 lines in one session segment is not a reachable state; the
    -- CHECK below pins the only invalid value.
    seg_line    INTEGER NOT NULL,

    -- THE HASHED TIMESTAMP. TEXT, verbatim, never reparsed, never reformatted.
    -- This is the whole design: chain.compute_chain hashes canonical JSON of
    -- this string, so a TIMESTAMPTZ round trip (which normalises offset
    -- spelling, fractional seconds and the trailing Z) breaks chain-head parity
    -- -- the single gate that proves the mirror.
    -- NULLABLE on purpose: the ledger reader checks key PRESENCE only, so a row
    -- {"ts": null, ...} is legal, reconstructs as None, and hashes as
    -- "ts":null. A NOT NULL here could only be satisfied by coercing it to ''
    -- -- which changes the hash. See view mindhive.events_anomalies.
    ts          TEXT COLLATE "C",

    -- Ordering key, generated. Mirrors `ev.ts or ""` in events.read_all
    -- exactly. COALESCE is IMMUTABLE, so this is a legal generated column
    -- (unlike the timestamptz cast -- see ts_utc). Indexed instead of `ts` so
    -- NULL and '' can never disagree with Python about which sorts first.
    -- COLLATE "C" for the same reason as every other text column: this is the
    -- column the ledger order is actually taken on.
    ts_key      TEXT COLLATE "C" NOT NULL
                GENERATED ALWAYS AS (COALESCE(ts, '')) STORED,

    -- Queryable UTC instant. NOT generated: Postgres requires a generated
    -- column's expression to be IMMUTABLE, and every text->timestamp path
    -- (text::timestamptz, text::timestamp, to_timestamp(text,text)) is STABLE
    -- because it depends on DateStyle and TimeZone -- GENERATED ALWAYS AS
    -- (ts::timestamptz) STORED fails at CREATE TABLE with "generation
    -- expression is not immutable". Populated by the loader from Python, NULL
    -- when `ts` is not the canonical YYYY-MM-DDTHH:MM:SSZ shape events.now_iso
    -- produces. NULL is a reportable anomaly, never a load failure: reads stay
    -- total. TIMESTAMPTZ rather than TIMESTAMP so interval arithmetic against
    -- now() is unambiguous.
    ts_utc      TIMESTAMPTZ,

    -- The hashed session_id field (NOT the filename -- `segment` is that).
    -- TEXT not VARCHAR(n): ids are uuid4, "manual", and "research-<run_id>",
    -- with no enforced length anywhere. COLLATE "C" so equality and ordering
    -- are byte-wise. Nullable for the same reason as `ts`.
    session_id  TEXT COLLATE "C",

    -- The hashed `type` field, renamed for clarity at the SQL surface. Names do
    -- not affect hashing; the DAL aliases it back to `type` when it rebuilds an
    -- Event. TEXT with COLLATE "C" and NO FK to event_type_registry:
    -- append_event validates membership at write time, the ledger holds rows
    -- written by every past version, and an FK would refuse to mirror a row the
    -- file ledger legitimately contains -- i.e. it would break parity to
    -- enforce a rule the source of truth does not enforce retroactively.
    event_type  TEXT COLLATE "C",

    -- JSONB, not JSON/TEXT, because payload search needs containment and a GIN
    -- index. Safe for hashing because canonical_json re-sorts keys in Python,
    -- so JSONB's internal key reordering is invisible to the chain. NOT NULL is
    -- correct even though a payload may be JSON null: 'null'::jsonb is a VALUE,
    -- not SQL NULL.
    payload     JSONB NOT NULL,

    -- Same reasoning. NOT NULL with no DEFAULT: the loader always writes an
    -- explicit value, because '[]' (key absent -> dataclass default) and 'null'
    -- (key present, null) hash differently and a column default would silently
    -- merge the two cases.
    tags        JSONB NOT NULL,

    -- Mirror bookkeeping only. Never hashed, never part of any ordering, which
    -- is why a non-deterministic DEFAULT now() is harmless here and would not
    -- be on any column above.
    loaded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT events_seg_line_nonneg CHECK (seg_line >= 0),
    -- The natural key of a file row. Makes the load idempotent (ON CONFLICT DO
    -- NOTHING) and makes "was any row loaded twice?" a constraint rather than a
    -- test -- a duplicated row changes the chain head, so it must be impossible
    -- rather than merely unlikely.
    CONSTRAINT events_natural_key UNIQUE (project, segment, seg_line)
);

-- Rows the file ledger legitimately contains but that a naive NOT NULL schema
-- would have rejected. Empty on a healthy store; non-empty is a fact to look
-- at, not an error to raise (reads stay total).
CREATE OR REPLACE VIEW mindhive.events_anomalies AS
SELECT project, segment, seg_line, global_seq,
       (ts IS NULL)                        AS ts_null,
       (ts IS NOT NULL AND ts_utc IS NULL) AS ts_unparsed,
       (session_id IS NULL)                AS session_null,
       (event_type IS NULL)                AS type_null,
       (jsonb_typeof(payload) <> 'object') AS payload_not_object,
       (jsonb_typeof(tags)    <> 'array')  AS tags_not_array
FROM mindhive.events
WHERE ts IS NULL OR session_id IS NULL OR event_type IS NULL
   OR (ts IS NOT NULL AND ts_utc IS NULL)
   OR jsonb_typeof(payload) <> 'object' OR jsonb_typeof(tags) <> 'array';

-- Which types are semantic vs deterministic, so SQL can classify without a
-- hardcoded list drifting from events.py. Rewritten wholesale from
-- pgschema.EVENT_TYPE_CLASSES on every migrate; a drift test asserts that table
-- equals events.VALID_TYPES.
CREATE TABLE IF NOT EXISTS mindhive.event_type_registry (
    -- TEXT COLLATE "C": joined against events.event_type, which is byte-wise.
    -- A locale collation on one side of a join key and not the other is how two
    -- columns that look equal stop matching.
    event_type TEXT COLLATE "C" PRIMARY KEY,
    -- TEXT rather than an enum type: an enum needs its own migration to gain a
    -- value, and the CHECK expresses the same closed set re-runnably.
    class      TEXT COLLATE "C" NOT NULL
               CHECK (class IN ('semantic','deterministic'))
);

-- One row per mirrored namespace: the last rebuild and its parity verdict.
-- Exists so `hive pg status` and every tool's freshness stamp can answer "is
-- the mirror trustworthy?" without recomputing a 20 MB fold.
CREATE TABLE IF NOT EXISTS mindhive.mirror_state (
    -- TEXT COLLATE "C" to match events.project exactly; PK because one row per
    -- namespace is the whole shape of this table.
    project            TEXT COLLATE "C" PRIMARY KEY,
    -- INTEGER: bumped by any migration that changes row shape, so a reader can
    -- refuse a mirror built by an older loader.
    schema_version     INTEGER NOT NULL,
    -- BIGINT: == len(events.read_all(project)) at rebuild time. BIGINT rather
    -- than INTEGER because this counts the whole ledger, not one segment.
    row_count          BIGINT  NOT NULL,
    -- TEXT COLLATE "C": a hex sha256 digest. Compared for equality only, and
    -- byte-wise equality is the only kind that means anything for a digest.
    file_head          TEXT COLLATE "C" NOT NULL,
    -- TEXT COLLATE "C": the same digest recomputed from the MIRROR's rows. Two
    -- columns rather than one boolean because "they differ" is not actionable
    -- and "they differ, and here are both heads" is.
    pg_head            TEXT COLLATE "C" NOT NULL,
    -- BOOLEAN, durable: the tools REFUSE to answer when this is false, because
    -- unlike staleness a parity failure is unbounded -- rows may be missing,
    -- duplicated or misordered and you cannot say which.
    parity_ok          BOOLEAN NOT NULL,
    -- JSONB {segment_name: [size, mtime_ns]} -- the same stat-only stamp
    -- dashboard_memo._ledger_fingerprint uses. JSONB so the per-segment diff
    -- ("stale by roughly one session") is computable, not just the verdict.
    -- Lets a reader detect "files moved since the mirror was built" for the
    -- cost of one scandir.
    ledger_fingerprint JSONB NOT NULL,
    -- TIMESTAMPTZ: bookkeeping, never hashed, so now() is fine here.
    rebuilt_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mindhive.schema_migrations (
    -- TEXT COLLATE "C": the filename, applied in lexicographic order, so the
    -- ordering must be byte-wise rather than locale-dependent.
    filename   TEXT COLLATE "C" PRIMARY KEY,
    -- TEXT COLLATE "C": sha256 of the file's bytes. apply_migrations REFUSES to
    -- continue when a recorded file's content changed -- silently re-running it
    -- and silently skipping it are both worse than stopping.
    sha256     TEXT COLLATE "C" NOT NULL,
    -- TIMESTAMPTZ: bookkeeping only, never hashed and never ordered on (the
    -- filename is the order), so a non-deterministic DEFAULT now() is safe.
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
